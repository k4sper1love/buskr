package callbacks

import (
	"context"

	"github.com/k4sper1love/buskr/internal/domain/user"
	"github.com/k4sper1love/buskr/internal/transport/telegram/ctxkey"
	"github.com/k4sper1love/buskr/internal/transport/telegram/render"
	"github.com/k4sper1love/buskr/internal/usecase/profile"
	"gopkg.in/telebot.v3"
)

type ProfileCallbacks struct {
	uc       *profile.Usecase
	renderer *render.Renderer
}

func NewProfileCallbacks(uc *profile.Usecase, renderer *render.Renderer) *ProfileCallbacks {
	return &ProfileCallbacks{
		uc:       uc,
		renderer: renderer,
	}
}

func (h *ProfileCallbacks) HandleProfile(c telebot.Context) error {
	ctx := c.Get("ctx").(context.Context)

	u, err := ctxkey.GetUser(c)
	if err != nil {
		return err
	}

	rep, err := h.uc.Profile(ctx, u)
	if err != nil {
		return err
	}

	c.Respond(&telebot.CallbackResponse{})
	if rep.IsEmpty() {
		return nil
	}

	return h.renderer.Render(c, rep)
}

